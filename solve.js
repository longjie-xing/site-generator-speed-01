// Fast static site generator: a from-scratch reimplementation of makefun-site 1.0.0's
// build semantics, written for speed. Every output byte matches the reference program;
// only the work is different (no regexes on hot paths, no per-character escaping,
// memoized slugs/dates, direct-render Markdown, compiled templates).

// ---------------------------------------------------------------- text

const ESCAPES = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };

/** `s` HTML-escaped (identical to a per-character escape table). */
const ESC_TEST = /[&<>"']/; // no /g: test() always scans from 0, safe to share
const ESC_REPLACE = /[&<>"']/g; // replace() resets lastIndex, safe to share
const ESC_MAP = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };
const escReplacer = c => ESC_MAP[c];

/** HTML-escape `s`. One test pass; only strings with a special char pay for a
 * single replace pass (callback per matched char, usually 0-2 per chunk). */
function escStr(s) {
  if (!ESC_TEST.test(s)) return s;
  return s.replace(ESC_REPLACE, escReplacer);
}

/** Append `s` HTML-escaped to the output array `out`. */
function pushEsc(out, s) {
  out.push(escStr(s));
}

/** The most characters a slug keeps before a collision suffix. */
const SLUG_MAX = 64;

const slugCache = new Map();

/**
 * The slug of `text`: NFKD, combining marks dropped, A-Z lowered, every run of
 * characters other than a-z and 0-9 one "-", none at either end, at most 64 characters
 * (a "-" left at the cut dropped), and "untitled" when nothing is left.
 */
function slugify(text) {
  const hit = slugCache.get(text);
  if (hit !== undefined) return hit;
  let out;
  // Fast path: pure ASCII needs no NFKD normalisation and holds no combining marks.
  let ascii = true;
  for (let i = 0; i < text.length; i++) {
    if (text.charCodeAt(i) > 127) { ascii = false; break; }
  }
  if (ascii) {
    let res = '';
    let gap = false;
    for (let i = 0; i < text.length; i++) {
      const c = text.charCodeAt(i);
      let keep = -1;
      if (c >= 65 && c <= 90) keep = c + 32;
      else if ((c >= 97 && c <= 122) || (c >= 48 && c <= 57)) keep = c;
      if (keep === -1) {
        if (res.length > 0) gap = true;
        continue;
      }
      if (gap) res += '-';
      gap = false;
      res += String.fromCharCode(keep);
    }
    out = res.slice(0, SLUG_MAX).replace(/-+$/, '');
    if (out === '') out = 'untitled';
  } else {
    const plain = text.normalize('NFKD').replace(/\p{M}/gu, '');
    let res = '';
    let gap = false;
    for (const ch of plain) {
      let keep = null;
      if (ch >= 'A' && ch <= 'Z') keep = ch.toLowerCase();
      else if ((ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9')) keep = ch;
      if (keep === null) {
        gap = res.length > 0;
        continue;
      }
      if (gap) res += '-';
      gap = false;
      res += keep;
    }
    out = res.slice(0, SLUG_MAX).replace(/-+$/, '');
    if (out === '') out = 'untitled';
  }
  if (slugCache.size < 8192) slugCache.set(text, out);
  return out;
}

/** `slug` made unique against `taken` (and added to it): slug, slug-2, slug-3 ... */
function uniqueSlug(slug, taken) {
  let out = slug;
  for (let n = 2; taken.has(out); n++) out = `${slug}-${n}`;
  taken.add(out);
  return out;
}

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

const dateCache = new Map();

/** A YYYY-MM-DD date in words, from the string alone: "2026-11-09" is "9 November 2026". */
function longDate(date) {
  let hit = dateCache.get(date);
  if (hit === undefined) {
    const y = date.slice(0, 4);
    const m = Number(date.slice(5, 7));
    const d = Number(date.slice(8, 10));
    hit = `${d} ${MONTHS[m - 1]} ${y}`;
    if (dateCache.size < 4096) dateCache.set(date, hit);
  }
  return hit;
}

/** The words of a body: its runs of characters other than whitespace. */
function wordsOf(text) {
  let n = 0;
  let inWord = false;
  for (let i = 0; i < text.length; i++) {
    const c = text.charCodeAt(i);
    // ASCII fast path: every ASCII whitespace is <= 32, every other ASCII
    // char is a word char. Only non-ASCII chars need the full whitespace set.
    if (c <= 32) { inWord = false; continue; }
    if (c < 128) { if (!inWord) { inWord = true; n++; } continue; }
    const ws = c === 160 || c === 5760 || (c >= 8192 && c <= 8202) || c === 8232 ||
      c === 8233 || c === 8239 || c === 8287 || c === 12288 || c === 65279;
    if (ws) inWord = false;
    else if (!inWord) { inWord = true; n++; }
  }
  return n;
}

